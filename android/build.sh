#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")"
SDK="${ANDROID_SDK_ROOT:-/opt/homebrew/share/android-commandlinetools}"
JDK="${HOUSE_TV_JDK:-/opt/homebrew/opt/openjdk@17}"
BT="$SDK/build-tools/36.0.0"
ANDROID_JAR="$SDK/platforms/android-34/android.jar"
export JAVA_HOME="$JDK"
export PATH="$JDK/bin:$PATH"
mkdir -p build/classes build/dex dist
rm -rf assets/web
mkdir -p assets/web
cp -R ../web/dist/. assets/web/
rm -f build/resources.zip build/resources.apk build/unsigned.apk
"$BT/aapt2" compile --dir res -o build/resources.zip
"$BT/aapt2" link -o build/resources.apk -I "$ANDROID_JAR" --manifest AndroidManifest.xml --java build/generated --auto-add-overlay -A assets build/resources.zip
# The Luma launchers whose widgets may read this home: HOUSE_TV_LUMA_CERTS (SHA-256 of signing certificates,
# comma-separated), plus the official Luma release key, plus, for local builds only, the key of a Luma built next to
# this folder. A build signed with HOUSE_TV_KEYSTORE (a release) never picks up a local key by itself.
LUMA_CERTS="${HOUSE_TV_LUMA_CERTS:-}"
if [ -z "${HOUSE_TV_KEYSTORE:-}" ]; then
    for keystore in ../../luma-tv/.signing/local.keystore ../../launcher/.signing/local.keystore; do
        if [ -f "$keystore" ]; then
            LUMA_CERTS="$LUMA_CERTS,$("$JDK/bin/keytool" -list -v -keystore "$keystore" -storepass android -alias luma-local 2>/dev/null | sed -n 's/^.*SHA256: //p' | tr -d ':' | tr 'A-F' 'a-f')"
        fi
    done
fi
LUMA_CERTS="$LUMA_CERTS,22827fdf43a69ecdb377b734d4a02c5e96b6e0bbb1654aa297e47208585854d3" # the official Luma release key
python3 - "$LUMA_CERTS" > build/generated/dev/housecontrol/tv/Trust.java <<'PY'
import re, sys
pins = sorted({c for c in sys.argv[1].lower().split(",") if re.fullmatch(r"[0-9a-f]{64}", c)})
print("package dev.housecontrol.tv;\n/** Generated by build.sh: signing certificates of the Luma builds allowed to read this home. */")
print("final class Trust { static final String[] LUMA = {" + ", ".join('"%s"' % c for c in pins) + "}; }")
PY
find src build/generated -name '*.java' > build/sources.txt
javac -encoding UTF-8 --release 8 -classpath "$ANDROID_JAR" -d build/classes @build/sources.txt
find build/classes -name '*.class' > build/classes.txt
"$BT/d8" --lib "$ANDROID_JAR" --min-api 26 --output build/dex @build/classes.txt
cp build/resources.apk build/unsigned.apk
(cd build/dex && zip -q -u ../unsigned.apk classes.dex)
"$BT/zipalign" -f -p 4 build/unsigned.apk build/aligned.apk
# HOUSE_TV_KEYSTORE picks another signing key, for example a release key: HOUSE_TV_KEYSTORE=.signing/release.keystore
KEYSTORE="${HOUSE_TV_KEYSTORE:-.signing/local.keystore}"
if [ ! -f .signing/local.keystore ] && [ "$KEYSTORE" = .signing/local.keystore ]; then
    mkdir -p .signing
    keytool -genkeypair -keystore .signing/local.keystore -storepass android -keypass android -alias house-tv-local -keyalg RSA -keysize 2048 -validity 10000 -dname 'CN=House Control TV, O=Local build'
fi
"$BT/apksigner" sign --ks "$KEYSTORE" --ks-pass pass:android --ks-key-alias house-tv-local --out dist/house-control-tv.apk build/aligned.apk
"$BT/apksigner" verify dist/house-control-tv.apk
ls -lh dist/house-control-tv.apk
